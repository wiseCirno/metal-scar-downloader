export function safeNeteaseErrorCode(error) {
  const text = typeof error === "string" ? error : error instanceof Error ? error.message : ""
  const code = text.match(/NETEASE_[A-Z_]+/)?.[0]
  return safeNeteaseErrorCodes.has(code) ? code : null
}

