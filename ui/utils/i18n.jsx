export function translate(language, key, values = {}) {
  let text = messages[language]?.[key] || messages["zh-Hans"][key] || key
  for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value))
  return text
}

export const I18nContext = createContext(null)
export function I18nProvider({ children }) {
  const [language, setLanguage] = useState("zh-Hans")
  useEffect(() => {
    getConfig()
      .then((config) => setLanguage(config.language || "zh-Hans"))
      .catch(() => {})
  }, [])
  const value = useMemo(
    () => ({ language, setLanguage, t: (key) => messages[language]?.[key] || messages["zh-Hans"][key] || key }),
    [language],
  )
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}
export function useI18n() {
  return useContext(I18nContext)
}
